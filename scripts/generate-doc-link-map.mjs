#!/usr/bin/env node

/**
 * generate-doc-link-map.mjs
 *
 * Build-time generator for the in-app help-link resolution map described in
 * docs/help-pages-plan.md §4.4.
 *
 * Two outputs:
 *
 *   1. `docs/help/providers/<slug>.md` for every entry in PROVIDER_PAGES
 *      (scripts/lib/help-pages.mjs) — keeps all 32 provider pages on one
 *      template (plan §2.11). Existing pages are left untouched unless
 *      `--force` is passed, so hand-reviewed edits are never clobbered.
 *   2. `webview-ui/src/utils/docLinkMap.generated.ts` — the shipped, static
 *      slug -> repo path map. Keys are the normalised slugs derived from the
 *      `docs/help/**` tree; values are the repo-relative path without the
 *      `docs/help/` prefix and without `.md`.
 *
 * Modes:
 *   (default)  write both outputs.
 *   --check    do not write; exit 1 if the map on disk differs from what would
 *              be generated, if a provider page is missing, or if a provider
 *              page's committed bytes differ from the rendered template
 *              (M1 — a stale/hand-edited provider page must fail CI, not just a
 *              missing one). Mirrors the generate-announcements +
 *              verify-announcement-version pattern.
 *
 * Usage (repo root):
 *   node scripts/generate-doc-link-map.mjs
 *   node scripts/generate-doc-link-map.mjs --check
 *   node scripts/generate-doc-link-map.mjs --force
 *
 * Env overrides (used by the spec):
 *   ROO_HELP_ROOT      docs/help root (default: <repo>/docs/help)
 *   ROO_DOC_LINK_MAP   generated file path (default:
 *                      <repo>/webview-ui/src/utils/docLinkMap.generated.ts)
 */

import * as fs from "node:fs"
import * as path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

import { logStep, logEndGroup, logInfo, logOk, logError, logSuccess } from "./lib/logger.mjs"
import { PROVIDER_PAGES, renderProviderPage } from "./lib/help-pages.mjs"

const TAG = "GENERATE:DOC-LINK-MAP"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "..")

const DEFAULT_HELP_ROOT = path.join(ROOT, "docs", "help")
const DEFAULT_MAP_PATH = path.join(ROOT, "webview-ui", "src", "utils", "docLinkMap.generated.ts")

/**
 * History of every help slug that has ever shipped, stored under `docs/help/`.
 * A released slug is immutable (plan §4.6): `--check` fails if a recorded slug
 * no longer has a `docs/help/<slug>.md`, so a rename/delete is caught in CI
 * instead of silently 404-ing the `blob/master` links baked into older builds.
 */
export const RELEASED_SLUGS_FILE = "released-slugs.json"

/**
 * Recursively collects every `*.md` file under `dir`, returning paths relative
 * to `dir` with forward slashes.
 * @param {string} dir
 * @param {string} [base]
 * @returns {string[]}
 */
export function collectMarkdownFiles(dir, base = dir) {
	if (!fs.existsSync(dir)) return []
	const out = []
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const abs = path.join(dir, entry.name)
		if (entry.isDirectory()) {
			out.push(...collectMarkdownFiles(abs, base))
		} else if (entry.isFile() && entry.name.toLowerCase().endsWith(".md")) {
			out.push(path.relative(base, abs).split(path.sep).join("/"))
		}
	}
	return out
}

/**
 * Derives the normalised slug for a help-page file.
 * @param {string} rel - Path relative to docs/help, e.g. "features/skills.md".
 * @returns {string}
 */
export function slugForFile(rel) {
	return rel.replace(/\.md$/i, "").trim().toLowerCase()
}

/**
 * Builds the map entries from the help-page tree.
 * @param {string} helpRoot
 * @returns {{ slug: string; path: string }[]}
 */
export function buildEntries(helpRoot) {
	return collectMarkdownFiles(helpRoot)
		.map((rel) => ({ slug: slugForFile(rel), path: slugForFile(rel) }))
		.sort((a, b) => a.slug.localeCompare(b.slug))
}

/**
 * Renders the generated TypeScript module. Formatting matches the repo
 * prettier config (tabs, no semicolons, double quotes) so the file is stable
 * under `prettier --write`.
 * @param {{ slug: string; path: string }[]} entries
 * @returns {string}
 */
export function renderMapModule(entries) {
	const lines = []
	lines.push("// AUTO-GENERATED by scripts/generate-doc-link-map.mjs - do not edit by hand.")
	lines.push("// Source of truth: the docs/help/**/*.md tree. Regenerate with:")
	lines.push("//   node scripts/generate-doc-link-map.mjs")
	lines.push("")
	lines.push("export const DOC_LINK_MAP: Record<string, { path: string }> = {")
	if (entries.length === 0) {
		lines.push("\t// (no help pages found)")
	}
	for (const entry of entries) {
		lines.push(`\t"${entry.slug}": { path: "${entry.path}" },`)
	}
	lines.push("}")
	lines.push("")
	return lines.join("\n")
}

/**
 * Writes the provider pages that do not yet exist (or all of them with force).
 * @param {string} helpRoot
 * @param {boolean} force
 * @returns {{ written: string[]; skipped: string[] }}
 */
export function writeProviderPages(helpRoot, force = false) {
	const written = []
	const skipped = []
	const providersDir = path.join(helpRoot, "providers")
	for (const page of PROVIDER_PAGES) {
		const file = path.join(providersDir, `${page.slug}.md`)
		const content = renderProviderPage(page)
		if (!force && fs.existsSync(file)) {
			skipped.push(`providers/${page.slug}.md`)
			continue
		}
		fs.mkdirSync(path.dirname(file), { recursive: true })
		fs.writeFileSync(file, content, "utf-8")
		written.push(`providers/${page.slug}.md`)
	}
	return { written, skipped }
}

/**
 * Reads the released-slug history (`docs/help/released-slugs.json`). Returns
 * `null` when the file is absent so callers can skip enforcement on fresh
 * checkouts and temp fixtures that do not carry a history file.
 * @param {string} helpRoot
 * @returns {Set<string> | null} normalised slugs, or null when unavailable.
 */
export function readReleasedSlugs(helpRoot) {
	const file = path.join(helpRoot, RELEASED_SLUGS_FILE)
	if (!fs.existsSync(file)) return null
	try {
		const parsed = JSON.parse(fs.readFileSync(file, "utf-8"))
		const list = Array.isArray(parsed) ? parsed : parsed.releasedSlugs
		if (!Array.isArray(list)) return null
		return new Set(list.map((slug) => String(slug).trim().toLowerCase()))
	} catch {
		return null
	}
}

/**
 * Merges `slugs` into the released-slug history (creating the file when absent)
 * and writes it back in a stable, sorted form. Env-free and idempotent so the
 * write path can be re-run without churn.
 * @param {string} helpRoot
 * @param {string[]} slugs
 * @returns {string[]} the slugs that were newly added to the history.
 */
export function writeReleasedSlugs(helpRoot, slugs) {
	const existing = readReleasedSlugs(helpRoot) ?? new Set()
	const added = []
	for (const slug of slugs) {
		const normalised = slug.trim().toLowerCase()
		if (existing.has(normalised)) continue
		existing.add(normalised)
		added.push(normalised)
	}
	const file = path.join(helpRoot, RELEASED_SLUGS_FILE)
	fs.mkdirSync(path.dirname(file), { recursive: true })
	fs.writeFileSync(file, `${JSON.stringify({ releasedSlugs: [...existing].sort() }, null, "\t")}\n`, "utf-8")
	return added.sort()
}

/**
 * Pure verdict: is the map on disk in sync with the help-page tree?
 * @param {{ helpRoot: string; mapPath: string; force?: boolean }} opts
 * @returns {{ ok: boolean; expected: string; actual: string; entries: number; problems: string[] }}
 */
export function checkDocLinkMap({ helpRoot, mapPath, force = false }) {
	const problems = []

	for (const page of PROVIDER_PAGES) {
		const file = path.join(helpRoot, "providers", `${page.slug}.md`)
		if (!fs.existsSync(file)) {
			problems.push(`missing provider page: docs/help/providers/${page.slug}.md`)
			continue
		}
		// M1: byte-compare the committed page against the rendered template so a
		// stale or hand-edited provider page fails --check (existence alone let a
		// drifted page advertise a wrong endpoint while the gate stayed green).
		const committed = fs.readFileSync(file, "utf-8")
		const rendered = renderProviderPage(page)
		if (committed !== rendered) {
			problems.push(
				`stale provider page: docs/help/providers/${page.slug}.md differs from the rendered template (run: node scripts/generate-doc-link-map.mjs --force)`,
			)
		}
	}

	const entries = buildEntries(helpRoot)
	const expected = renderMapModule(entries)
	let actual = ""
	try {
		actual = fs.readFileSync(mapPath, "utf-8")
	} catch (error) {
		problems.push(`cannot read generated map ${mapPath}: ${error.message}`)
	}
	if (actual && actual !== expected) {
		problems.push("docLinkMap.generated.ts is out of sync with docs/help/** (regenerate it)")
	}

	// F4 / plan §4.6: a released slug is immutable. When the history file exists,
	// every recorded slug must still have a page — a rename/delete is a hard
	// failure, never a silent 404 for the `blob/master` links baked into older
	// builds. Absent history (fresh checkout / fixture) skips enforcement.
	const released = readReleasedSlugs(helpRoot)
	if (released) {
		const present = new Set(entries.map((entry) => entry.slug))
		for (const slug of [...released].sort()) {
			if (present.has(slug)) continue
			problems.push(
				`released slug "${slug}" no longer has docs/help/${slug}.md — never rename or delete a released slug; restore it as a "moved" redirect stub (see docs/help-pages-plan.md §4.6)`,
			)
		}
	}

	void force
	return { ok: problems.length === 0, expected, actual, entries: entries.length, problems }
}

async function main() {
	const checkOnly = process.argv.includes("--check")
	const force = process.argv.includes("--force")
	const helpRoot = process.env.ROO_HELP_ROOT ? path.resolve(process.env.ROO_HELP_ROOT) : DEFAULT_HELP_ROOT
	const mapPath = process.env.ROO_DOC_LINK_MAP ? path.resolve(process.env.ROO_DOC_LINK_MAP) : DEFAULT_MAP_PATH

	logStep(
		TAG,
		checkOnly ? "Checking the generated doc-link map (dry run)" : "Generating provider help pages + doc-link map",
	)
	logInfo(TAG, `docs/help root: ${helpRoot}`)
	logInfo(TAG, `generated map:  ${mapPath}`)

	if (checkOnly) {
		const result = checkDocLinkMap({ helpRoot, mapPath })
		if (!result.ok) {
			for (const problem of result.problems) logError(TAG, problem)
			logError(TAG, "Run: node scripts/generate-doc-link-map.mjs")
			process.exit(1)
		}
		logOk(TAG, `${result.entries} map entries in sync; all ${PROVIDER_PAGES.length} provider pages present`)
		logEndGroup()
		logSuccess(TAG, "Generated doc-link map is up to date.")
		process.exit(0)
	}

	const { written, skipped } = writeProviderPages(helpRoot, force)
	if (written.length > 0) logOk(TAG, `wrote ${written.length} provider page(s)`)
	if (skipped.length > 0) logInfo(TAG, `kept ${skipped.length} existing provider page(s) (use --force to overwrite)`)

	const entries = buildEntries(helpRoot)
	fs.mkdirSync(path.dirname(mapPath), { recursive: true })
	fs.writeFileSync(mapPath, renderMapModule(entries), "utf-8")
	logOk(TAG, `wrote ${entries.length} entries to ${path.relative(ROOT, mapPath)}`)

	// Record every authored slug as released (plan §4.6) so a later rename/delete
	// is caught by `--check` rather than silently breaking shipped deep links.
	const added = writeReleasedSlugs(
		helpRoot,
		entries.map((entry) => entry.slug),
	)
	if (added.length > 0) logOk(TAG, `recorded ${added.length} new released slug(s) in ${RELEASED_SLUGS_FILE}`)

	logEndGroup()
	logSuccess(TAG, "Provider help pages and doc-link map generated.")
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
	main().catch((error) => {
		logError(TAG, `generation failed: ${error.message}`)
		process.exit(1)
	})
}
